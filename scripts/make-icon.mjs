// Renders the a-orbit icon from its SVG sources (build/brand) into every
// format the app needs, so there is one source of truth and no opaque binary
// nobody can regenerate.
// Output: build/icon.png (1024), build/icon.ico, build/icon.icns and
// src/main/brand/trayGlyph.ts (alpha masks of the tray glyph, baked into main) and
// build/tray/trayTemplate{,@2x}.png (the Mac menu-bar image).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Resvg } from '@resvg/resvg-js'
import { ICNS_TYPES, ICO_SIZES, TRAY_SIZES, alphaOf, encodeIcns, encodeIco } from './iconFormats.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const master = readFileSync(resolve(root, 'build/brand/qclod.svg'), 'utf8')
const tray = readFileSync(resolve(root, 'build/brand/tray.svg'), 'utf8')

function render(svg, size) {
  return new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render()
}

const pngs = new Map()
function masterPng(size) {
  if (!pngs.has(size)) pngs.set(size, render(master, size).asPng())
  return pngs.get(size)
}

const out = resolve(root, 'build')
mkdirSync(out, { recursive: true })

writeFileSync(resolve(out, 'icon.png'), masterPng(1024))
writeFileSync(resolve(out, 'icon.ico'), encodeIco(ICO_SIZES.map((size) => ({ size, png: masterPng(size) }))))
writeFileSync(
  resolve(out, 'icon.icns'),
  encodeIcns(Object.entries(ICNS_TYPES).map(([type, size]) => ({ type, png: masterPng(size) })))
)

const glyph = TRAY_SIZES.map((size) => {
  const image = render(tray, size)
  const mask = alphaOf(image.pixels, size)
  return `  ${size}: '${Buffer.from(mask).toString('base64')}'`
})
mkdirSync(resolve(root, 'src/main/brand'), { recursive: true })
writeFileSync(
  resolve(root, 'src/main/brand/trayGlyph.ts'),
  `// GENERATED by scripts/make-icon.mjs from build/brand/tray.svg — do not edit by hand.
// Base64 alpha mask (size × size bytes) of the tray glyph; the tone is set in code.
export const TRAY_GLYPH: Readonly<Record<16 | 24 | 32, string>> = {
${glyph.join(',\n')}
}
`
)
// The Mac's menu-bar template image: the same black glyph, 16 and 32 px (@2x).
// tray.svg is black on transparent, which is exactly what a template image is.
mkdirSync(resolve(out, 'tray'), { recursive: true })
writeFileSync(resolve(out, 'tray/trayTemplate.png'), render(tray, 16).asPng())
writeFileSync(resolve(out, 'tray/trayTemplate@2x.png'), render(tray, 32).asPng())

console.log('icon: build/icon.{png,ico,icns}, build/tray/trayTemplate{,@2x}.png and src/main/brand/trayGlyph.ts written')
